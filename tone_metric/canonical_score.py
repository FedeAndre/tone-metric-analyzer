from __future__ import annotations

"""Canonical score-time recovery for scanned PDF scores.

The tone-metric algorithm must operate in musical time, not in PDF geometry.  This
module reads Audiveris' saved notation graph and builds a measure-local metric grid
first.  Recognized note/rest columns are then assigned to that grid.  PDF x/y is kept
only as provenance for the later drawing stage.

Important rules implemented here:
- augmentation dots extend duration but never create attacks;
- tie continuations occupy a score position but do not create attacks;
- rests occupy score time but do not create attacks;
- an attack in any other voice at the same position still creates a global hit;
- simultaneous/near-coincident noteheads are one physical attack column;
- Audiveris BEGIN slot times are useful constraints, but contradictory ones cannot
  reorder the printed score.  A maximum feasible monotonic subset is used as anchors;
- missing semantic slots are filled on an exact rational metric lattice.  Geometry is
  used only to choose among positions already generated by that lattice.
"""

